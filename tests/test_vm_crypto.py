@pytest.mark.parametrize("size", SIZES)
def test_digests_match_hashlib(peer, size):
    # Every byte value appears in the larger inputs; the seed keeps a failure reproducible.
    data = random.Random(size).randbytes(size)
    result = run_vm(peer, stdin=data)
    assert result.code == 0, result.stderr
    lines = result.stdout.strip().split("\n")
    expected = []
    for name in DIGESTS:
        digest = hashlib.new(name, data)
        expected += [list(digest.digest()), digest.hexdigest()]
    assert [json.loads(line) if line.startswith("[") else line for line in lines] == expected


HMAC_KEY_SIZES = [0, 1, 20, 63, 64, 65, 127, 128, 129, 131, 1000]
HMAC_DATA_SIZES = [0, 1, 55, 64, 111, 128, 129, 4096 + 7, 65536]


def test_hmacs_match_python_hmac(hmac_peer):
    # Every key size with every data size; the seed keeps a failure reproducible.
    rng = random.Random(4231)
    cases = [(rng.randbytes(k), rng.randbytes(d)) for k in HMAC_KEY_SIZES for d in HMAC_DATA_SIZES]
    stdin = json.dumps({"cases": [{"key": list(key), "data": list(data)} for key, data in cases]})
    result = run_vm(hmac_peer, stdin=stdin)
    assert result.code == 0, result.stderr
    for (key, data), macs in zip(cases, json.loads(result.stdout), strict=True):
        sha256 = hmac.new(key, data, hashlib.sha256)
        sha512 = hmac.new(key, data, hashlib.sha512)
        assert macs == {"sha256": list(sha256.digest()), "sha256_hex": sha256.hexdigest(),
                        "sha512": list(sha512.digest()), "sha512_hex": sha512.hexdigest()}, (len(key), len(data))


COMPARE_SIZES = [0, 1, 16, 32, 64, 1000, 65536]


def compare_pairs(rng):
    """Pairs of byte strings: equal, one byte changed (first, middle, last), a prefix, and another length."""
    pairs = []
    for size in COMPARE_SIZES:
        data = rng.randbytes(size)
        pairs += [(data, bytes(data)), (data, rng.randbytes(size + 1)), (data, data + b"\0")]
        for at in {0, size // 2, size - 1} if size else ():
            changed = bytearray(data)
            changed[at] ^= 1 << rng.randrange(8)
            pairs.append((data, bytes(changed)))
        if size:
            pairs.append((data, data[:-1]))
    return pairs + [(b, a) for a, b in pairs]


def test_secure_compare_matches_python_compare_digest(secure_compare_peer):
    pairs = compare_pairs(random.Random(5))
    stdin = json.dumps({"pairs": [{"a": list(a), "b": list(b)} for a, b in pairs]})
    result = run_vm(secure_compare_peer, stdin=stdin)
    assert result.code == 0, result.stderr
    answers = json.loads(result.stdout)
    assert answers == [hmac.compare_digest(a, b) for a, b in pairs]
    assert True in answers and False in answers


# A list item that is not a byte halts at the list argument that holds it, from "[" to past "]": (call, arguments,
# index of the bad one). The HMAC key is the first argument and the data the second; secure_compare takes a and b.
NOT_BYTES = [("Digest.sha256", ["[1, %s, 3]" % bad], 0) for bad in ("256", "-1", "1048576")] + [
    (call, ["[1, 256]"], 0) for call in ("Base64.encode64", "Base64.strict_encode64", "Base64.urlsafe_encode64",
                                         "Digest.hexencode", "Digest.md5", "Digest.md5_hexdigest", "Digest.sha1",
                                         "Digest.sha1_hexdigest", "Digest.sha256_hexdigest", "Digest.sha512",
                                         "Digest.sha512_hexdigest")] + [
    (call, arguments, bad) for call in ("HMAC.sha256", "HMAC.sha256_hexdigest", "HMAC.sha512", "HMAC.sha512_hexdigest",
                                        "HMAC.secure_compare")
    for arguments, bad in ((["[1, 256]", "[2]"], 0), (["[1]", "[2, -1]"], 1))]


def assert_halts_at_the_argument(tmp_path, call, arguments, bad, code):
    source = tmp_path / "bad.agc"
    source.write_text("def main() -> Void\n  puts(%s(%s))\nend\n" % (call, ", ".join(arguments)))
    result = run_vm(compile_agc(source, tmp_path / "bad.agcb"), "--json")
    assert result.code == 1
    diagnostic = json.loads(result.stderr.strip().split("\n")[-1])
    assert diagnostic["code"] == code
    span = diagnostic["range"]
    start = len("  puts(%s(%s" % (call, "".join(argument + ", " for argument in arguments[:bad]))) + 1
    assert (span["start"]["line"], span["start"]["column"]) == (2, start)
    assert (span["end"]["line"], span["end"]["column"]) == (2, start + len(arguments[bad]))


@pytest.mark.parametrize("call, arguments, bad", NOT_BYTES)
def test_a_value_that_is_not_a_byte_halts_at_the_argument(tmp_path, call, arguments, bad):
    assert_halts_at_the_argument(tmp_path, call, arguments, bad, "RUNTIME-INVALID-NUMBER")


def ruby_encode64(data):
    # Ruby's encode64 is pack("m"): 45 bytes a line, each line one b2a_base64 call with its newline; nothing for b"".
    return "".join(binascii.b2a_base64(data[i:i + 45]).decode() for i in range(0, len(data), 45))


def strict_or_none(text):
    # Ruby's strict_decode64 takes only canonical padded base64: the text Python decodes and encodes back unchanged
    # (that also rejects spare bits that are not zero, which Python alone ignores).
    try:
        data = base64.b64decode(text, validate=True)
    except ValueError:
        return None
    return list(data) if base64.b64encode(data).decode() == text else None


def urlsafe_or_none(text):
    # Ruby's urlsafe_decode64 pads text that does not end in "=" to a multiple of four, maps -_ to +/ and decodes
    # strictly.
    if not text.endswith("=") and len(text) % 4:
        text += "=" * (-len(text) % 4)
    return strict_or_none(text.replace("-", "+").replace("_", "/"))


def hex_or_none(text):
    try:
        return list(binascii.unhexlify(text))
    except ValueError:
        return None


def lenient(text):
    # Ruby's decode64 on text with no "=": the alphabet characters in groups of four, a lone last one dropped. Python
    # decodes the same characters once they are padded.
    digits = "".join(c for c in text if c in BASE64_ALPHABET)
    if len(digits) % 4 == 1:
        digits = digits[:-1]
    return list(base64.b64decode(digits + "=" * (-len(digits) % 4)))


def ruby_decode64(text):
    # A model of the group loop of Ruby's decode64 (unpack "m" in pack.c), for the text with "=" that Python's decoder
    # reads otherwise: other characters are skipped, a "=" in the first two places of a group too, one in the last
    # two places ends the text, and a last group of two or three digits gives one or two bytes.
    digits = {ord(c): i for i, c in enumerate(BASE64_ALPHABET)}
    out, group = [], []
    for byte in text.encode():
        if byte == ord("=") and len(group) >= 2:
            break
        if byte in digits:
            group.append(digits[byte])
        if len(group) == 4:
            value = group[0] << 18 | group[1] << 12 | group[2] << 6 | group[3]
            out += [value >> 16, value >> 8 & 255, value & 255]
            group = []
    if len(group) >= 2:
        out.append((group[0] << 2 | group[1] >> 4) & 255)
    if len(group) == 3:
        out.append((group[1] << 4 | group[2] >> 2) & 255)
    return out


def generated_texts(rng):
    """(text, decode64 answer from Python's base64, or None where only the ruby_decode64 model has one) pairs."""
    texts = []
    for size in range(40):
        data = rng.randbytes(size)
        canonical = base64.b64encode(data).decode()
        noisy = list(canonical)
        for _ in range(rng.randint(1, 4)):
            noisy.insert(rng.randint(0, len(noisy)), rng.choice(NOISE))
        noisy = "".join(noisy)
        # Python's non-validating decode drops the noise bytes and reads the padding as Ruby does here.
        texts += [(canonical, list(data)), (ruby_encode64(data), list(data)),
                  (base64.urlsafe_b64encode(data).decode().rstrip("="), None),
                  ("%s=%s" % (canonical.rstrip("="), noisy), None),
                  (noisy, list(base64.b64decode(noisy.encode(), validate=False))),
                  (data.hex(), lenient(data.hex())), (data.hex().upper(), lenient(data.hex().upper()))]
        if size % 3:
            # Another last digit before the padding: often spare bits that are not zero, which only decode64 takes.
            cut = canonical.rstrip("=")
            spare = cut[:-1] + rng.choice(BASE64_ALPHABET) + canonical[len(cut):]
            texts.append((spare, list(base64.b64decode(spare))))
    alphabets = [BASE64_ALPHABET, BASE64_ALPHABET + "=-_", BASE64_ALPHABET + "==" + NOISE, "0123456789abcdefABCDEFg "]
    for _ in range(600):
        chars = rng.choice(alphabets)
        text = "".join(rng.choice(chars) for _ in range(rng.randint(0, 13)))
        texts.append((text, lenient(text) if "=" not in text else None))
    return texts


def test_base64_and_hex_match_python(base64_peer):
    rng = random.Random(757)
    datas = [rng.randbytes(size) for size in BASE64_SIZES]
    texts = generated_texts(rng)
    cases = {"bytes": [list(data) for data in datas], "texts": [text for text, _ in texts]}
    result = run_vm(base64_peer, stdin=json.dumps(cases))
    assert result.code == 0, result.stderr
    answers = json.loads(result.stdout)
    for data, encoded in zip(datas, answers["encoded"], strict=True):
        urlsafe = base64.urlsafe_b64encode(data).decode()
        assert encoded == [ruby_encode64(data), base64.b64encode(data).decode(), urlsafe, urlsafe.rstrip("="),
                           binascii.hexlify(data).decode()], len(data)
    for (text, expected), decoded in zip(texts, answers["decoded"], strict=True):
        # Where Python has the answer, the model must agree with it, so the model is checked on those texts too.
        model = ruby_decode64(text)
        assert expected is None or model == expected, text
        assert decoded["lenient"] == model, text
        assert decoded["strict"] == strict_or_none(text), text
        assert decoded["urlsafe"] == urlsafe_or_none(text), text
        assert decoded["hex"] == hex_or_none(text), text


# SecureRandom sizes: none, one, Ruby's default 16, the upper bound (1 MiB) and some between.
RANDOM_SIZES = [0, 1, 2, 15, 16, 17, 64, 1000, 65536, 1048576]
UUID_DRAWS = 2000
UUID_FORM = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}")


def draw(peer):
    result = run_vm(peer, stdin=json.dumps({"sizes": RANDOM_SIZES, "uuids": UUID_DRAWS}))
    assert result.code == 0, result.stderr
    return json.loads(result.stdout)


def test_secure_random_formats_match_python(secure_random_peer):
    drawn = draw(secure_random_peer)
    for size, data, text in zip(RANDOM_SIZES, drawn["bytes"], drawn["hex"], strict=True):
        assert len(data) == size and all(0 <= b <= 255 for b in data)
        assert re.fullmatch("[0-9a-f]{%d}" % (2 * size), text), size
    # 1 MiB of uniform bytes misses one of the 256 values with chance below 256 * e ** -4096.
    assert set(drawn["bytes"][-1]) == set(range(256))
    for text in drawn["uuids"]:
        assert UUID_FORM.fullmatch(text), text
        parsed = uuid.UUID(text)
        assert (parsed.version, parsed.variant, str(parsed)) == (4, uuid.RFC_4122, text)
    # 122 random bits a uuid: a repeat among 2000 has chance below 2 ** -100. The two bits after the variant are
    # random too, so each of 8, 9, a and b leads the fourth group (a missing one has chance below 4 * 0.75 ** 2000).
    assert len(set(drawn["uuids"])) == UUID_DRAWS
    assert {text[19] for text in drawn["uuids"]} == set("89ab")


def test_secure_random_differs_between_runs(secure_random_peer):
    # Not seeded, unlike Random: two runs give other bytes (16 bytes repeat with chance 2 ** -128).
    first, second = draw(secure_random_peer), draw(secure_random_peer)
    for size, a, b in zip(RANDOM_SIZES, first["bytes"], second["bytes"], strict=True):
        assert size < 16 or a != b, size
    assert set(first["uuids"]).isdisjoint(second["uuids"])



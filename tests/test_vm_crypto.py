"""The Digest hashes against Python's hashlib, the HMACs and HMAC.secure_compare
against Python's hmac, Base64 and hex against Python's base64 and binascii, and the SecureRandom
formats against Python's uuid and re, on every system.

The peer program (tests/fixtures/digest-peer.agc) hashes all of its stdin with
MD5, SHA-1, SHA-256 and SHA-512; the inputs cover the padding boundaries of the
64-byte blocks (55, 56 and 64 bytes) and of the 128-byte SHA-512 blocks (111,
112 and 128), inputs of several blocks and 1 MiB.
tests/fixtures/hmac-peer.agc computes HMAC-SHA256 and HMAC-SHA512 of generated
keys and data in one run: keys on both sides of the 64- and 128-byte blocks
(a longer key is hashed first) and data from empty to 64 KiB.
tests/fixtures/secure-compare-peer.agc compares generated pairs of byte lists:
equal ones, ones that differ in one byte and ones of other lengths.
tests/fixtures/base64-peer.agc encodes generated byte lists and decodes
generated texts in one run. SecureRandom gives new bytes on every run, so
tests/fixtures/secure-random-peer.agc is checked on properties only: sizes, the
byte range, the hex and uuid forms, and that draws differ. The bad-input cases
check the code and the span of the diagnostic.
"""

"""Bytes.decode and String.encode against Python's codecs, through tests/fixtures/text-codec-peer.agc.

One run of the peer answers every case: generated texts encoded in each encoding (the bytes must match Python's,
and decoding Python's bytes must give the text back), generated byte strings decoded in each encoding (valid ones give
Python's text, invalid ones an error whose offset is Python's UnicodeDecodeError.start), texts that a one-byte encoding
cannot hold (the index is UnicodeEncodeError.start), every name of each encoding, and every byte of the one-byte
encodings both ways, which checks the ISO-8859-15 and Windows-1252 tables of vm/text_codec.c entry by entry.

Python reads a plain UTF-16 or UTF-32 input without a byte order mark in the byte order of the machine and writes the
plain forms that way; Agentica reads and writes them big-endian, as the Unicode standard says, so the expected answer
of a plain form without a mark is the one of the BE form, and an encoded plain form is the mark FE FF and BE units.
The error texts and the fixed cases are the VM fixture text-codecs.
"""
import json
import random
import re

import pytest

from tests.agentica_test import FIXTURES, compile_agc, run_vm

UNICODE = ["utf-8", "utf-16", "utf-16le", "utf-16be", "utf-32", "utf-32le", "utf-32be"]
BYTE_CODECS = ["ascii", "latin-1", "iso-8859-15", "cp1252"]
# The one-byte encodings that define every byte, so that no decode in them fails.
TOTAL_CODECS = {"latin-1", "iso-8859-15"}
# Every name the VM takes for each encoding (vm/text_codec.c), written in the case and with the `_` the lookup
# reads as `-`; Python's codecs.lookup takes each one.
NAMES = {
    "utf-8": ["utf-8", "utf8", "UTF-8", "UTF_8"],
    "utf-16": ["utf-16", "utf16", "UTF-16"],
    "utf-16le": ["utf-16le", "utf-16-le", "UTF_16_LE"],
    "utf-16be": ["utf-16be", "utf-16-be", "UTF-16BE"],
    "utf-32": ["utf-32", "utf32", "UTF-32"],
    "utf-32le": ["utf-32le", "utf-32-le", "UTF_32_LE"],
    "utf-32be": ["utf-32be", "utf-32-be", "UTF-32BE"],
    "ascii": ["ascii", "us-ascii", "US_ASCII"],
    "latin-1": ["latin-1", "latin1", "iso-8859-1", "iso8859-1", "ISO_8859-1", "l1", "cp819"],
    "iso-8859-15": ["iso-8859-15", "iso8859-15", "ISO_8859-15", "latin9", "L9"],
    "cp1252": ["cp1252", "windows-1252", "Windows-1252", "CP1252"],
}
MARKS = {"utf-16": (b"\xfe\xff", b"\xff\xfe"), "utf-32": (b"\x00\x00\xfe\xff", b"\xff\xfe\x00\x00")}
# Bytes that make the decoders take every path: UTF-8 leads, continuations and bytes never allowed; and UTF-16 and
# UTF-32 units with surrogates, a mark and values above U+10FFFF.
UTF8_BYTES = [0x41, 0x7F, 0x80, 0xBF, 0xC0, 0xC2, 0xDF, 0xE0, 0xED, 0xA0, 0x9F, 0xEF, 0xF0, 0x90, 0xF4, 0x8F, 0xF5, 0xFF]
UTF16_UNITS = [0x0041, 0x00E9, 0x20AC, 0xD800, 0xDBFF, 0xDC00, 0xDFFF, 0xFEFF, 0xFFFE]
UTF32_UNITS = [0x41, 0xE9, 0xFEFF, 0xD800, 0xDFFF, 0x10FFFF, 0x110000, 0xFFFE0000]


@pytest.fixture(scope="module")
def peer(tmp_path_factory):
    return compile_agc(FIXTURES / "text-codec-peer.agc", tmp_path_factory.mktemp("codec") / "text-codec-peer.agcb")


def python_name(encoding, data=b""):
    """The Python codec that reads data as the VM does: a plain form without a mark is the BE one."""
    if encoding in MARKS and not data.startswith(MARKS[encoding]):
        return encoding + "-be"
    return encoding


def python_encode(text, encoding):
    if encoding in MARKS:
        return MARKS[encoding][0] + text.encode(encoding + "-be")
    return text.encode(encoding)


def expected_decode(data, encoding):
    try:
        return {"passed": True, "text": data.decode(python_name(encoding, data))}
    except UnicodeDecodeError as e:
        return {"passed": False, "at": ("byte", e.start)}


def expected_encode(text, encoding):
    try:
        return {"passed": True, "data": list(python_encode(text, encoding))}
    except UnicodeEncodeError as e:
        return {"passed": False, "at": ("index", e.start)}


def offset(message):
    """The offset that ends an error text: `... at byte N` or `... at index N`."""
    found = re.search(r" at (byte|index) (\d+)$", message)
    assert found, message
    return found.group(1), int(found.group(2))


def random_text(rng, top):
    """A text of code points up to top, with no surrogate (a String never holds one)."""
    points = []
    for _ in range(rng.randrange(12)):
        cp = rng.choice([rng.randrange(0x80), rng.randrange(0x100), rng.randrange(top + 1)])
        points.append(cp if not 0xD800 <= cp <= 0xDFFF else 0xFFFD)
    return "".join(map(chr, points))


def random_units(rng, units, width, order):
    data = b"".join(rng.choice(units).to_bytes(width, order) for _ in range(rng.randrange(6)))
    return data + bytes(rng.randrange(256) for _ in range(rng.randrange(width)))


def alphabet(encoding):
    """The characters of a one-byte encoding: those of the bytes it defines."""
    found = []
    for byte in range(256):
        try:
            found.append(bytes([byte]).decode(encoding))
        except UnicodeDecodeError:
            pass
    return found


def cases(rng):
    """(case, expected answer) pairs for the peer."""
    found = []
    alphabets = {encoding: alphabet(encoding) for encoding in BYTE_CODECS}
    for _ in range(60):
        text = random_text(rng, 0x10FFFF)
        for encoding in UNICODE:
            found.append(({"op": "encode", "encoding": encoding, "text": text}, expected_encode(text, encoding)))
            data = python_encode(text, encoding)
            found.append(({"op": "decode", "encoding": encoding, "data": data}, expected_decode(data, encoding)))
        for encoding in BYTE_CODECS:
            short = "".join(rng.choice(alphabets[encoding]) for _ in range(rng.randrange(12)))
            for sample in (short, text):
                found.append(({"op": "encode", "encoding": encoding, "text": sample}, expected_encode(sample, encoding)))
    for _ in range(200):
        data = bytes(rng.choice(UTF8_BYTES) for _ in range(rng.randrange(8)))
        found.append(({"op": "decode", "encoding": "utf-8", "data": data}, expected_decode(data, "utf-8")))
        data = bytes(rng.randrange(256) for _ in range(rng.randrange(8)))
        for encoding in BYTE_CODECS:
            found.append(({"op": "decode", "encoding": encoding, "data": data}, expected_decode(data, encoding)))
        for encoding, units, width in (("utf-16", UTF16_UNITS, 2), ("utf-32", UTF32_UNITS, 4)):
            for order, suffix in (("little", "le"), ("big", "be")):
                data = random_units(rng, units, width, order)
                for name in (encoding + suffix, encoding):
                    found.append(({"op": "decode", "encoding": name, "data": data}, expected_decode(data, name)))
    # Every byte and every character near the tables: the C1 range, Latin-1 and the characters the tables hold.
    near = [chr(cp) for cp in range(0x80, 0x100)] + [c for e in BYTE_CODECS for c in alphabets[e] if ord(c) >= 0x100]
    for encoding in BYTE_CODECS:
        for byte in range(256):
            data = bytes([byte])
            found.append(({"op": "decode", "encoding": encoding, "data": data}, expected_decode(data, encoding)))
        for char in near:
            found.append(({"op": "encode", "encoding": encoding, "text": char}, expected_encode(char, encoding)))
    for encoding, names in NAMES.items():
        sample = "ab" if encoding == "ascii" else "aé"
        for name in names:
            found.append(({"op": "encode", "encoding": name, "text": sample}, expected_encode(sample, encoding)))
            data = python_encode(sample, encoding)
            found.append(({"op": "decode", "encoding": name, "data": data}, expected_decode(data, encoding)))
    return found


def test_the_codecs_match_python(peer):
    pairs = cases(random.Random(889))
    stdin = json.dumps({"cases": [
        {"op": c["op"], "encoding": c["encoding"], "data": list(c.get("data", b"")), "text": c.get("text", "")}
        for c, _ in pairs
    ]})
    result = run_vm(peer, stdin=stdin)
    assert result.code == 0, result.stderr
    answers = json.loads(result.stdout)
    assert len(answers) == len(pairs)
    for (case, expected), answer in zip(pairs, answers):
        assert answer["passed"] == expected["passed"], (case, answer)
        if not expected["passed"]:
            assert offset(answer["message"]) == expected["at"], (case, answer)
        elif case["op"] == "encode":
            assert answer["data"] == expected["data"], case
        else:
            assert answer["text"] == expected["text"], case
    # The generated inputs reach both answers of every decoder.
    for encoding in UNICODE + BYTE_CODECS:
        outcomes = {e["passed"] for c, e in pairs if c["encoding"] == encoding and c["op"] == "decode"}
        assert outcomes == ({True} if encoding in TOTAL_CODECS else {True, False}), encoding


def test_an_unknown_encoding_is_an_error_both_ways(peer):
    stdin = json.dumps({"cases": [
        {"op": "decode", "encoding": "utf-8-sig", "data": [97], "text": ""},
        {"op": "encode", "encoding": "koi8-r", "data": [], "text": "a"},
        {"op": "encode", "encoding": "utf-8\u0000", "data": [], "text": "a"},
    ]})
    result = run_vm(peer, stdin=stdin)
    assert result.code == 0, result.stderr
    assert [a["passed"] for a in json.loads(result.stdout)] == [False, False, False]
